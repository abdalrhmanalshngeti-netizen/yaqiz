// تعقيم نص لإدراج آمن داخل HTML (إيميلات إشعارات، قوالب مُنشأة من بيانات
// مستخدَمين) — نفس الدالة المستخدَمة أصلًا بـsupport.controller.js لنفس السبب،
// مُستخرَجة هنا لملف مشترك عشان أي قالب إيميل آخر يعقّم بها بدل تكرارها محليًا
// أو نسيانها (كان إيميل تسجيل شركة جديدة بـregister.controller.js بلا أي تعقيم)
exports.escapeHtml = function escapeHtml(str) {
  return String(str ?? '').replace(/[&<>"']/g, c => ({ '&':'&amp;', '<':'&lt;', '>':'&gt;', '"':'&quot;', "'":'&#39;' }[c]));
};
