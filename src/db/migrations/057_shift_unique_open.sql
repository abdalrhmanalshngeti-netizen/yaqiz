-- يمنع أكثر من وردية مفتوحة واحدة لنفس الموظف بمستوى قاعدة البيانات — الفحص
-- التطبيقي بـ openShift (SELECT ثم INSERT بلا قفل) كان عرضة لسباق حقيقي بين
-- طلبين متزامنين (نقرة مزدوجة، إعادة محاولة شبكة) ينتج عنه ورديتان مفتوحتان
-- بنفس الوقت، تفسدان تسوية الصندوق (المبيعات تُنسب لأيهما تُقفَل أولًا)
CREATE UNIQUE INDEX IF NOT EXISTS idx_shifts_one_open_per_user
  ON shifts(user_id) WHERE status = 'open';
